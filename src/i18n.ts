const TABLES: Record<Exclude<Lang, 'en'>, Tr> = { fa: FA, es: ES, de: DE, fr: FR, ar: AR, zh: ZH, ja: JA };
const INDEX = new Map<string, number>(EN.map((s, i) => [s, i]));

let current: Lang = 'en';

export function resolve(pref: string): Lang {
  const want = pref === 'system' ? (navigator.language || 'en').slice(0, 2).toLowerCase() : pref;
  return (LANGS.some((l) => l.id === want) ? want : 'en') as Lang;
}

export function lang(): Lang {
  return current;
}

export function t(s: string, vars?: Record<string, string | number>): string {
  let out = s;
  if (current !== 'en') {
    const i = INDEX.get(s);
    if (i !== undefined) out = TABLES[current][i] ?? s;
  }
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}

const original = new WeakMap<Node, string>();
const ATTRS = ['placeholder', 'aria-label', 'title'] as const;

export function translateDom(root: ParentNode = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const p = n.parentElement;
    if (!p || p.closest('script,style,svg,[data-i18n-skip]')) continue;
    if (!original.has(n)) original.set(n, n.textContent ?? '');
    const src = original.get(n)!;
    const key = src.trim().replace(/\s+/g, ' ');
    if (!key || !INDEX.has(key)) continue;
    const lead = src.match(/^\s*/)?.[0] ?? '';
    const tail = src.match(/\s*$/)?.[0] ?? '';
    n.textContent = lead + t(key) + tail;
  }
  root.querySelectorAll<HTMLElement>('*').forEach((el) => {
    for (const a of ATTRS) {
      const v = el.getAttribute(a);
      if (v === null) continue;
      const k = `data-i18n-${a}`;
      if (!el.hasAttribute(k)) el.setAttribute(k, v);
      const src = el.getAttribute(k)!;
      if (INDEX.has(src)) el.setAttribute(a, t(src));
    }
  });
}

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'fa' || l === 'ar' ? 'rtl' : 'ltr';
  translateDom();
}
